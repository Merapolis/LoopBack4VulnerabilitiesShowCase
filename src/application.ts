import 'reflect-metadata';
import {RestApplication} from '@loopback/rest';
import {ApplicationConfig} from '@loopback/core';
import {HealthController} from './controllers/health.controller';
import {DbDataSource} from './datasources/db.datasource';
import {DocumentRepository} from './repositories/document.repository';
import {DocumentController} from './controllers/document.controller';
import {ApiIdentityRepository} from './repositories/api-identity.repository';
import {DemoController} from './controllers/demo.controller';
import {LandingController} from './controllers/landing.controller';

export class App extends RestApplication {
  constructor(options: ApplicationConfig = {}) {
    // Bind to the loopback interface only. Callers may override the
    // configuration, for example by using an ephemeral port in tests.
    super({
      ...options,
      rest: {
        host: '127.0.0.1',
        port: 3000,
        ...options.rest,
      },
    });

    // Register health controller.
    this.controller(HealthController);

    // Register datasource, repository, and document controller explicitly.
    this.bind('datasources.db').to(new DbDataSource());
    this.bind('repositories.DocumentRepository').toClass(DocumentRepository);
    this.controller(DocumentController);

    // Deliberately vulnerable demo workflow, isolated to the
    // demo/wildcard-oracle branch.
    this.bind('repositories.ApiIdentityRepository').toClass(
      ApiIdentityRepository,
    );
    this.controller(DemoController);

    // Presentation-only landing page for the vulnerable demo branch.
    this.controller(LandingController);
  }

  // Seed deterministic synthetic documents. The memory database starts
  // empty on application restart, so the count guard preserves idempotency.
  private async seedDocuments(): Promise<void> {
    const repo = await this.get<DocumentRepository>(
      'repositories.DocumentRepository',
    );

    const count = (await repo.count()).count;

    if (count !== 0) {
      return;
    }

    // IDs are generated by the connector and must not be supplied here.

    // Original fixtures retained for existing examples and tests.
    await repo.create({
      title: 'Public Document',
      content: 'Public content',
      ownerId: 'alice',
      visibility: 'public',
    });

    await repo.create({
      title: 'Alice Private',
      content: 'Alice secret',
      ownerId: 'alice',
      visibility: 'private',
    });

    await repo.create({
      title: 'Bob Private',
      content: 'Bob secret',
      ownerId: 'bob',
      visibility: 'private',
    });

    // Additional Alice documents.
    await repo.create({
      title: 'Alice Public Roadmap',
      content: 'Synthetic milestones for a fictional product roadmap.',
      ownerId: 'alice',
      visibility: 'public',
    });

    await repo.create({
      title: 'Alice Research Notes',
      content: 'Synthetic observations from a fictional research exercise.',
      ownerId: 'alice',
      visibility: 'private',
    });

    // Additional Bob document.
    await repo.create({
      title: 'Bob Public Notes',
      content: 'Synthetic engineering notes from a fictional project.',
      ownerId: 'bob',
      visibility: 'public',
    });

    // Carol documents.
    await repo.create({
      title: 'Carol Public Announcement',
      content: 'Synthetic announcement for a fictional team.',
      ownerId: 'carol',
      visibility: 'public',
    });

    await repo.create({
      title: 'Carol Private Report',
      content: 'Synthetic quarterly figures for a fictional organisation.',
      ownerId: 'carol',
      visibility: 'private',
    });

    // Dave documents.
    await repo.create({
      title: 'Dave Runbook',
      content: 'Synthetic restart instructions for a fictional service.',
      ownerId: 'dave',
      visibility: 'public',
    });

    await repo.create({
      title: 'Dave Incident Notes',
      content: 'Synthetic timeline for a fictional incident exercise.',
      ownerId: 'dave',
      visibility: 'private',
    });
  }

  // Seed fixed educational API identities independently of document seeding.
  // Every access ID contains four non-repeating uppercase characters.
  private async seedIdentities(): Promise<void> {
    const repo = await this.get<ApiIdentityRepository>(
      'repositories.ApiIdentityRepository',
    );

    const count = (await repo.count()).count;

    if (count !== 0) {
      return;
    }

    await repo.create({ownerId: 'alice', accessId: 'BLOG'});
    await repo.create({ownerId: 'bob', accessId: 'SAFE'});
    await repo.create({ownerId: 'carol', accessId: 'CODE'});
    await repo.create({ownerId: 'dave', accessId: 'DAVE'});
  }

  async start(): Promise<void> {
    await super.start();
    await this.seedDocuments();
    await this.seedIdentities();
  }
}

// If this file is executed directly, start the application.
if (require.main === module) {
  (async () => {
    const app = new App();
    await app.start();
    console.log('Server is running at http://127.0.0.1:3000');
  })();
}